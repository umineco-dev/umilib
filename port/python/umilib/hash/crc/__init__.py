"""Cyclic redundancy checks of any width up to 128 bits. Mirrors ``umilib::hash::crc``.

The register type ``W`` of the Rust types is chosen from the width, so one
:class:`CRCTable` and one :class:`CRC` hold any of them and values are Python
integers. :class:`CRCCatalogue` has every algorithm of the RevEng catalogue as
an attribute, named as in Rust (``CRC-32/ISO-HDLC`` is ``CRC32_ISO_HDLC``). A
:class:`CRC` keeps its table alive.
"""

from __future__ import annotations

import ctypes
from dataclasses import dataclass
from typing import Any

from umilib.ffi import U128, Bytes, Fields, Handle, Library, Preset, Text

P = "umilib_hash_crc"


@dataclass(frozen=True)
class CRCParameters:
    """A CRC algorithm in the Rocksoft model, with the names of the RevEng catalogue."""

    name: str
    width: int
    polynomial: int
    initial: int
    reflect_input: bool
    reflect_output: bool
    xor_output: int
    check: int
    residue: int

    def structure(self) -> Any:
        structure = Library.default().type(f"{P}_CRCParameters")()
        Fields.assign(structure, "width", self.width)
        structure.reflect_input = self.reflect_input
        structure.reflect_output = self.reflect_output
        for name in ("polynomial", "initial", "xor_output", "check", "residue"):
            setattr(structure, name, U128.from_int(getattr(self, name)))
        return structure


class CRCTable(Handle):
    """The parameters of a CRC and its table."""

    FREE = f"{P}_crc_table_free"

    def __init__(self, parameters: CRCParameters | None = None, pointer: int | None = None) -> None:
        """The table of ``parameters``; fails unless the width is 1 to 128 and every value fits it.
        A table not from the catalogue has an empty name."""
        if pointer is None:
            if parameters is None:
                raise TypeError("CRCTable needs parameters")
            structure = parameters.structure()
            pointer = Handle.create(f"{P}_crc_table_new", ctypes.byref(structure))
        super().__init__(pointer)

    @classmethod
    def new(cls, parameters: CRCParameters) -> CRCTable:
        return cls(parameters)

    def clone(self) -> CRCTable:
        return CRCTable(pointer=Handle.create(f"{P}_crc_table_clone", self.handle))

    def parameters(self) -> CRCParameters:
        structure = Library.default().type(f"{P}_CRCParameters")()
        self.library.call(f"{P}_crc_table_parameters", self.handle, ctypes.byref(structure))
        name = self.library.output(f"{P}_crc_table_name", self.handle).decode("utf-8")
        return CRCParameters(
            name=name,
            width=structure.width,
            polynomial=structure.polynomial.to_int(),
            initial=structure.initial.to_int(),
            reflect_input=structure.reflect_input,
            reflect_output=structure.reflect_output,
            xor_output=structure.xor_output.to_int(),
            check=structure.check.to_int(),
            residue=structure.residue.to_int(),
        )

    def __repr__(self) -> str:
        return f"CRCTable({self.parameters().name or 'custom'})"


