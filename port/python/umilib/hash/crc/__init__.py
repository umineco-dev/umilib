class CRC(Handle):
    """A CRC computation over its own copy of a :class:`CRCTable`."""

    FREE = f"{P}_crc_free"

    def __init__(self, table: CRCTable, pointer: int | None = None) -> None:
        if pointer is None:
            pointer = Handle.create(f"{P}_crc_new", table.handle)
        super().__init__(pointer)
        self.table = table

    @classmethod
    def new(cls, table: CRCTable) -> CRC:
        return cls(table)

    @staticmethod
    def checksum(table: CRCTable, data: bytes | bytearray | memoryview) -> int:
        """The CRC of ``data``."""
        out = U128()
        data, length = Bytes.readable(data)
        Library.default().call(f"{P}_crc_checksum", table.handle, data, length, ctypes.byref(out))
        return out.to_int()

    def clone(self) -> CRC:
        return CRC(self.table, Handle.create(f"{P}_crc_clone", self.handle))

    def update(self, data: bytes | bytearray | memoryview) -> None:
        data, length = Bytes.readable(data)
        self.library.call(f"{P}_crc_update", self.handle, data, length)

    def value(self) -> int:
        """The CRC of the input so far."""
        out = U128()
        self.library.call(f"{P}_crc_value", self.handle, ctypes.byref(out))
        return out.to_int()

    def remainder(self) -> int:
        """The CRC of the input so far before the final xor: after an error-free codeword, the residue."""
        out = U128()
        self.library.call(f"{P}_crc_remainder", self.handle, ctypes.byref(out))
        return out.to_int()

    def reset(self) -> None:
        self.library.call(f"{P}_crc_reset", self.handle)

    def __repr__(self) -> str:
        return f"CRC({self.table!r})"


