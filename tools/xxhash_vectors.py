#!/usr/bin/env python3
"""Writes ``tests/vectors/hash/xxhash/xxhash.txt``: outputs of the reference
xxHash implementation, which serve the Rust tests of ``umilib::hash::xxhash``
as an oracle independent of the code under test.

The reference is the single header ``xxhash.h`` of https://github.com/Cyan4973/xxHash
(BSD 2-Clause), given as the first argument; it is compiled with clang into a
program that prints the outputs. The inputs and secrets are generated by the
program from fixed formulas, so running the script again writes the same file.
Uses only the standard library.

    python3 tools/xxhash_vectors.py path/to/xxhash.h
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path


class XXHashVectors:
    ROOT = Path(__file__).resolve().parent.parent
    OUTPUT = ROOT / "tests" / "vectors" / "hash" / "xxhash" / "xxhash.txt"
    LENGTHS = list(range(0, 261)) + list(range(261, 2400, 17)) + list(range(2400, 12000, 503)) + [65536, 100003]
    PROGRAM = r"""
#define XXH_INLINE_ALL
#include "xxhash.h"
#include <stdio.h>
#include <stdlib.h>

/* The input: byte i is the top byte of a linear congruential sequence. */
static void fill(unsigned char *buffer, size_t length, unsigned int state) {
    for (size_t index = 0; index < length; index++) {
        state = state * 1664525u + 1013904223u;
        buffer[index] = (unsigned char)(state >> 24);
    }
}

static void print_bytes(const char *label, const unsigned char *bytes, size_t length) {
    printf("%s ", label);
    for (size_t index = 0; index < length; index++) printf("%02x", bytes[index]);
    printf("\n");
}

int main(int argc, char **argv) {
    static const size_t lengths[] = { LENGTHS };
    size_t count = sizeof(lengths) / sizeof(lengths[0]);
    size_t largest = lengths[count - 1];
    unsigned char *input = malloc(largest);
    unsigned char secret_a[137], secret_b[200], secret_c[136], secret_d[300];
    fill(input, largest, 0x9E3779B9u);
    fill(secret_a, sizeof(secret_a), 1u);
    fill(secret_b, sizeof(secret_b), 2u);
    fill(secret_c, sizeof(secret_c), 3u);
    fill(secret_d, sizeof(secret_d), 4u);
    print_bytes("secret a", secret_a, sizeof(secret_a));
    print_bytes("secret b", secret_b, sizeof(secret_b));
    print_bytes("secret c", secret_c, sizeof(secret_c));
    print_bytes("secret d", secret_d, sizeof(secret_d));
    for (size_t item = 0; item < count; item++) {
        size_t n = lengths[item];
        printf("xxh32 %zu 0 = %08x\n", n, XXH32(input, n, 0));
        printf("xxh32 %zu 9e3779b1 = %08x\n", n, XXH32(input, n, 0x9E3779B1u));
        printf("xxh64 %zu 0 = %016llx\n", n, (unsigned long long)XXH64(input, n, 0));
        printf("xxh64 %zu 9e3779b185ebca87 = %016llx\n", n, (unsigned long long)XXH64(input, n, 0x9E3779B185EBCA87ull));
        unsigned long long seeds[2] = { 0, 0x9E3779B185EBCA87ull };
        for (int s = 0; s < 2; s++) {
            printf("xxh3_64 %zu %llx = %016llx\n", n, seeds[s], (unsigned long long)XXH3_64bits_withSeed(input, n, seeds[s]));
            XXH128_hash_t h = XXH3_128bits_withSeed(input, n, seeds[s]);
            printf("xxh3_128 %zu %llx = %016llx%016llx\n", n, seeds[s], (unsigned long long)h.high64, (unsigned long long)h.low64);
        }
        printf("xxh3_64 %zu a = %016llx\n", n, (unsigned long long)XXH3_64bits_withSecret(input, n, secret_a, sizeof(secret_a)));
        printf("xxh3_64 %zu b = %016llx\n", n, (unsigned long long)XXH3_64bits_withSecret(input, n, secret_b, sizeof(secret_b)));
        printf("xxh3_64 %zu c = %016llx\n", n, (unsigned long long)XXH3_64bits_withSecret(input, n, secret_c, sizeof(secret_c)));
        printf("xxh3_64 %zu d = %016llx\n", n, (unsigned long long)XXH3_64bits_withSecret(input, n, secret_d, sizeof(secret_d)));
        XXH128_hash_t c = XXH3_128bits_withSecret(input, n, secret_c, sizeof(secret_c));
        XXH128_hash_t d = XXH3_128bits_withSecret(input, n, secret_d, sizeof(secret_d));
        printf("xxh3_128 %zu c = %016llx%016llx\n", n, (unsigned long long)c.high64, (unsigned long long)c.low64);
        printf("xxh3_128 %zu d = %016llx%016llx\n", n, (unsigned long long)d.high64, (unsigned long long)d.low64);
        XXH128_hash_t a = XXH3_128bits_withSecret(input, n, secret_a, sizeof(secret_a));
        XXH128_hash_t b = XXH3_128bits_withSecret(input, n, secret_b, sizeof(secret_b));
        printf("xxh3_128 %zu a = %016llx%016llx\n", n, (unsigned long long)a.high64, (unsigned long long)a.low64);
        printf("xxh3_128 %zu b = %016llx%016llx\n", n, (unsigned long long)b.high64, (unsigned long long)b.low64);
    }
    free(input);
    return 0;
}
"""

    @staticmethod
    def main() -> None:
        if len(sys.argv) != 2:
            sys.exit("usage: xxhash_vectors.py path/to/xxhash.h")
        header = Path(sys.argv[1]).resolve()
        program = XXHashVectors.PROGRAM.replace("LENGTHS", ", ".join(map(str, XXHashVectors.LENGTHS)))
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory) / "vectors.c"
            binary = Path(directory) / "vectors"
            source.write_text(program, encoding="utf-8")
            subprocess.run(["clang", "-std=c99", "-O1", "-I", str(header.parent), str(source), "-o", str(binary)], check=True)
            output = subprocess.run([str(binary)], check=True, capture_output=True, text=True).stdout
        lines = [
            "# Generated by tools/xxhash_vectors.py from the reference xxhash.h 0.8.3; do not edit.",
            "# The input of length n is the first n bytes of: state = state * 1664525 + 1013904223",
            "# (mod 2^32, from 0x9E3779B9), each byte the top byte of the new state; secrets a, b, c and d",
            "# (137, 200, 136 and 300 bytes) are made the same way from the states 1 to 4. Lines: function length key = value,",
            "# the key a seed in hexadecimal or a secret, the value in hexadecimal.",
        ]
        XXHashVectors.OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        XXHashVectors.OUTPUT.write_text("\n".join(lines) + "\n" + output, encoding="utf-8")


if __name__ == "__main__":
    XXHashVectors.main()
