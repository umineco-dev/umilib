#!/usr/bin/env python3
"""Writes ``src/hash/crc/catalogue.rs`` and the catalogue of
``port/python/umilib/hash/crc/__init__.py`` from ``tests/vectors/hash/crc/catalogue.txt``,
the parameter lines of the RevEng "Catalogue of parametrised CRC algorithms"
(https://reveng.sourceforge.io/crc-catalogue/all.htm). Each algorithm becomes a
constant of ``CRCCatalogue`` with the smallest register type that holds its
width, and an attribute of the Python ``CRCCatalogue``. Uses only the standard library.
"""

from __future__ import annotations

import re
from pathlib import Path


class CRCCatalogue:
    ROOT = Path(__file__).resolve().parent.parent
    INPUT = ROOT / "tests" / "vectors" / "hash" / "crc" / "catalogue.txt"
    OUTPUT = ROOT / "src" / "hash" / "crc" / "catalogue.rs"
    PYTHON = ROOT / "port" / "python" / "umilib" / "hash" / "crc" / "__init__.py"
    LINE = re.compile(
        r'width=(\d+)  poly=(0x[0-9a-f]+)  init=(0x[0-9a-f]+)  refin=(true|false)  refout=(true|false)  '
        r'xorout=(0x[0-9a-f]+)  check=(0x[0-9a-f]+)  residue=(0x[0-9a-f]+)  name="([A-Z0-9/-]+)"'
    )

    @staticmethod
    def register(width: int) -> str:
        return next(f"u{bits}" for bits in (8, 16, 32, 64, 128) if width <= bits)

    @staticmethod
    def identifier(name: str) -> str:
        return name.replace("CRC-", "CRC", 1).replace("/", "_").replace("-", "_")

    @staticmethod
    def main() -> None:
        entries = []
        names: dict[str, list[str]] = {f"u{bits}": [] for bits in (8, 16, 32, 64, 128)}
        for line in CRCCatalogue.INPUT.read_text().splitlines():
            match = CRCCatalogue.LINE.fullmatch(line)
            if match is None:
                raise SystemExit(f"unexpected line: {line}")
            width, poly, init, refin, refout, xorout, check, residue, name = match.groups()
            register = CRCCatalogue.register(int(width))
            names[register].append(CRCCatalogue.identifier(name))
            entries.append(
                f"    pub const {CRCCatalogue.identifier(name)}: &'static CRCTable<{register}> = &CRCTable::<{register}>::preset(CRCParameters {{\n"
                f'        name: "{name}",\n'
                f"        width: {width},\n"
                f"        polynomial: {poly},\n"
                f"        initial: {init},\n"
                f"        reflect_input: {refin},\n"
                f"        reflect_output: {refout},\n"
                f"        xor_output: {xorout},\n"
                f"        check: {check},\n"
                f"        residue: {residue},\n"
                f"    }});\n"
            )
        for register, identifiers in names.items():
            items = "".join(f"        CRCCatalogue::{identifier},\n" for identifier in identifiers)
            entries.append(
                f"    /// Every algorithm with a `{register}` register.\n"
                f"    pub const TABLES_{register.upper()}: &'static [&'static CRCTable<{register}>] = &[\n{items}    ];\n"
            )
        source = (
            "// Generated by tools/crc_catalogue.py from tests/vectors/hash/crc/catalogue.txt; do not edit.\n\n"
            "use super::{CRCParameters, CRCTable};\n\n"
            '/// Every algorithm of the RevEng "Catalogue of parametrised CRC algorithms",\n'
            "/// named after the catalogue (`CRC-32/ISO-HDLC` is `CRC32_ISO_HDLC`). The\n"
            "/// tables are built at compile time and only those used are kept.\n"
            "#[derive(Clone, Copy, Debug)]\n"
            "pub struct CRCCatalogue;\n\n"
            "#[rustfmt::skip]\n"
            "impl CRCCatalogue {\n" + "\n".join(entries) + "}\n"
        )
        CRCCatalogue.OUTPUT.write_text(source)
        attributes = "".join(
            f'    {CRCCatalogue.identifier(name)} = Preset(lambda: CRCCatalogue.find("{name}"))\n'
            for name in (CRCCatalogue.LINE.fullmatch(line).group(9) for line in CRCCatalogue.INPUT.read_text().splitlines())
        )
        python = CRCCatalogue.PYTHON.read_text()
        start = python.index("    # BEGIN CATALOGUE\n") + len("    # BEGIN CATALOGUE\n")
        end = python.index("    # END CATALOGUE\n")
        CRCCatalogue.PYTHON.write_text(python[:start] + attributes + python[end:])


if __name__ == "__main__":
    CRCCatalogue.main()
