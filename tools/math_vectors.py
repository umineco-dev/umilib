#!/usr/bin/env python3
"""Writes ``tests/vectors/math/python.txt``: arithmetic results computed with
Python's integers, which serve the Rust tests of ``umilib::math`` as an
oracle independent of the code under test.

Every line is ``operation precision operands... = results...`` in
hexadecimal. The values are drawn from a fixed seed, so running the script
again writes the same file. Uses only the standard library.
"""

from __future__ import annotations

import random
from pathlib import Path


class MathVectors:
    ROOT = Path(__file__).resolve().parent.parent
    OUTPUT = ROOT / "tests" / "vectors" / "math" / "python.txt"
    PRECISIONS = [64, 128, 256, 384, 576, 1024, 2048]
    COUNT = 12

    def __init__(self) -> None:
        self.random = random.Random(20261024)

    def value(self, bits: int) -> int:
        """A random value of up to ``bits`` bits, often at a boundary."""
        choice = self.random.randrange(6)
        if choice == 0:
            return (1 << bits) - 1 - self.random.randrange(4)
        if choice == 1:
            return 1 << self.random.randrange(bits)
        if choice == 2:
            return self.random.getrandbits(bits) >> self.random.randrange(bits)
        return self.random.getrandbits(bits)

    def modulus(self, bits: int) -> int:
        """A random odd modulus of exactly ``bits`` bits or, sometimes, fewer."""
        value = (self.random.getrandbits(bits) | (1 << (bits - 1))) >> self.random.choice([0, 0, 0, 1, bits // 2])
        return max(value | 1, 3)

    def lines(self) -> list[str]:
        lines = []
        for bits in MathVectors.PRECISIONS:
            for _ in range(MathVectors.COUNT):
                a, b = self.value(bits), self.value(bits)
                d = self.value(bits) or 1
                lines.append(f"div_rem {bits} {a:x} {d:x} = {a // d:x} {a % d:x}")
                lines.append(f"mul {bits} {a:x} {b:x} = {a * b:x}")
                m = self.modulus(bits)
                e = self.value(bits)
                lines.append(f"mod_mul {bits} {m:x} {a:x} {b:x} = {a * b % m:x}")
                lines.append(f"mod_add {bits} {m:x} {a:x} {b:x} = {(a + b) % m:x}")
                lines.append(f"mod_sub {bits} {m:x} {a:x} {b:x} = {(a - b) % m:x}")
                lines.append(f"mod_pow {bits} {m:x} {a:x} {e:x} = {pow(a, e, m):x}")
                try:
                    inverse = f"{pow(a, -1, m):x}"
                except ValueError:
                    inverse = "none"
                lines.append(f"mod_invert {bits} {m:x} {a:x} = {inverse}")
        return lines

    @staticmethod
    def main() -> None:
        header = [
            "# Generated by tools/math_vectors.py with Python integers; do not edit.",
            "# operation precision operands... = results..., in hexadecimal.",
        ]
        MathVectors.OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        MathVectors.OUTPUT.write_text("\n".join(header + MathVectors().lines()) + "\n", encoding="utf-8")


if __name__ == "__main__":
    MathVectors.main()
